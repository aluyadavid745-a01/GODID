const variants = (product: string, colors: Array<[string, string]>, sizes: string[], baseSku: string) =>
  colors.flatMap(([color], colorIndex) =>
    sizes.map((size, sizeIndex) => ({
      id: `${product}-${color.toLowerCase().replace(/\s/g, "-")}-${size.toLowerCase()}`,
      sku: `${baseSku}-${colorIndex + 1}${sizeIndex + 1}${size}`,
      color,
      colorHex: colors[colorIndex][1],
      size,
      inventory: Math.max(0, 18 - colorIndex * 4 - sizeIndex * 3),
      lowStockThreshold: 5,
    })),
  );

